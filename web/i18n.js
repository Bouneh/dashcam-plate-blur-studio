  let language;
  try { language = localStorage.getItem('plaque-studio-language') === 'fr' ? 'fr' : 'en'; }
  catch { language = 'en'; }

  function t(key, values = {}) {
    const template = messages[language][key] ?? messages.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
  }

  function applyStatic() {
    document.documentElement.lang = language;
    document.title = t('page_title');
    document.querySelector('meta[name="description"]').content = t('page_description');
    document.querySelectorAll('[data-i18n]').forEach((element) => { element.textContent = t(element.dataset.i18n); });
    document.querySelectorAll('[data-i18n-aria]').forEach((element) => { element.setAttribute('aria-label', t(element.dataset.i18nAria)); });
    document.querySelectorAll('[data-i18n-title]').forEach((element) => { element.title = t(element.dataset.i18nTitle); });
    document.querySelectorAll('.language-switch button').forEach((button) => {
      button.setAttribute('aria-pressed', String(button.dataset.lang === language));
    });
  }

  function setLanguage(value) {
    language = value === 'fr' ? 'fr' : 'en';
    try { localStorage.setItem('plaque-studio-language', language); } catch {}
    applyStatic();
  }

  return { t, applyStatic, setLanguage, get language() { return language; }, messages };
